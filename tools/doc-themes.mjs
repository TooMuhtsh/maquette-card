// Écrit la table des variables CSS publiques --maquette-* dans docs/reference.md et docs/reference.fr.md, entre les marqueurs
//   <!-- maquette-variables:start … -->  et  <!-- maquette-variables:end -->
// La table est générée depuis la source unique src/carte/themes-variables.js (VARIABLES_THEME) : la doc ne peut pas dériver.
//   node tools/doc-themes.mjs          réécrit les tables
//   node tools/doc-themes.mjs --check  code 1 si une table diffère de la source (rien n'est écrit) ; test : tests/node/test_themes_doc.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

export const RACINE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const DOCS = { en: "docs/reference.md", fr: "docs/reference.fr.md" };
const DEBUT = "<!-- maquette-variables:start (generated by tools/doc-themes.mjs from src/carte/themes-variables.js, do not edit) -->";
const FIN = "<!-- maquette-variables:end -->";

// table Markdown d'une langue, tirée du morceau source (autonome : déclarations const seulement)
export function tables(racine = RACINE) {
  const code = fs.readFileSync(path.join(racine, "src/carte/themes-variables.js"), "utf8");
  const t = vm.runInNewContext(`${code}\n;({ VARIABLES_THEME, tableVariablesTheme })`, {});
  return { en: t.tableVariablesTheme("en"), fr: t.tableVariablesTheme("fr"), variables: t.VARIABLES_THEME };
}
// texte de la doc avec la table remplacée ; null si les marqueurs manquent
export function remplacer(doc, table) {
  const a = doc.indexOf(DEBUT), b = doc.indexOf(FIN);
  if (a < 0 || b < a) return null;
  return `${doc.slice(0, a)}${DEBUT}\n${table}\n${doc.slice(b)}`;
}
// { fichier: "ok" | "differs" | "no markers" } ; ecrire = réécrit les fichiers qui diffèrent
export function synchroniser(racine = RACINE, ecrire = false) {
  const t = tables(racine), etat = {};
  for (const [langue, f] of Object.entries(DOCS)) {
    const p = path.join(racine, f), doc = fs.readFileSync(p, "utf8"), neuf = remplacer(doc, t[langue]);
    etat[f] = neuf === null ? "no markers" : neuf === doc ? "ok" : "differs";
    if (ecrire && etat[f] === "differs") { fs.writeFileSync(p, neuf); etat[f] = "written"; }
  }
  return etat;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const verifier = process.argv.includes("--check"), etat = synchroniser(RACINE, !verifier);
  for (const [f, e] of Object.entries(etat)) console.log(`${f}: ${e}`);
  if (Object.values(etat).some((e) => e === "no markers" || (verifier && e === "differs"))) process.exit(1);
}
